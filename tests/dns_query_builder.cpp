#include <gtest/gtest.h>
#include "dns/QueryBuilder.h"

/// QUERY BUILD TEST ///

TEST(DNSQueryBuilder, Standard) {
    dns::Question question("example.com", dns::QType::A);
    std::vector<std::uint8_t> actual = dns::buildQuery(question, 0xAB3E);
    std::vector<std::uint8_t> expected {
        0xAB, 0x3E, 0x01, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x07, 0x65, 0x78, 0x61, 0x6D, 0x70, 0x6C, 0x65, 0x03, 0x63, 0x6F, 0x6D, 0x00,
        0x00, 0x01, 0x00, 0x01
    };

    EXPECT_EQ(expected, actual);
}